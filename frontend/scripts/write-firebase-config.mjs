// Writes the generated, gitignored config files from environment variables:
//   src/app/firebase-config.ts   FIREBASE_* values
//   src/environment.ts   target, title and Firestore collection names
// Values come from the process environment, or from frontend/.env when it exists.
// Usage: node scripts/write-firebase-config.mjs [--target=local|beta|prd] [--allow-missing]
// The target picks the FIRESTORE_*_<TARGET> variables and defaults to local.
import {writeFileSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

try {
  process.loadEnvFile(resolve(root, '.env'));
} catch (err) {
  if (err.code !== 'ENOENT') throw err;
}

const TARGETS = ['local', 'beta', 'prd'];
const TITLE = 'Codex Bruxellensis';

const targetArg = process.argv.find(arg => arg.startsWith('--target='));
const target = targetArg ? targetArg.slice('--target='.length) : 'local';
if (!TARGETS.includes(target)) {
  console.error(`Unknown target "${target}", expected one of: ${TARGETS.join(', ')}`);
  process.exit(1);
}
const suffix = target.toUpperCase();

const FIREBASE = {
  apiKey: 'FIREBASE_API_KEY',
  authDomain: 'FIREBASE_AUTH_DOMAIN',
  databaseURL: 'FIREBASE_DATABASE_URL',
  projectId: 'FIREBASE_PROJECT_ID',
  storageBucket: 'FIREBASE_STORAGE_BUCKET',
  messagingSenderId: 'FIREBASE_MESSAGING_SENDER_ID',
  appId: 'FIREBASE_APP_ID'
};
const DATABASES = {
  codex: `FIRESTORE_CODEX_COLLECTION_${suffix}`,
  userData: `FIRESTORE_USER_DATA_COLLECTION_${suffix}`
};

const allowMissing = process.argv.includes('--allow-missing');
const missing = [...Object.values(FIREBASE), ...Object.values(DATABASES)].filter(name => !process.env[name]);

if (missing.length && !allowMissing) {
  console.error(`Missing environment variables: ${missing.join(', ')}`);
  console.error('Copy .env.example to .env and fill it in, or set them in the environment.');
  process.exit(1);
}

const resolveValues = names => Object.fromEntries(
  Object.entries(names).map(([key, name]) => [key, process.env[name] ?? ''])
);
const toLines = (values, indent) => Object.entries(values)
  .map(([key, value]) => `${indent}${key}: ${JSON.stringify(value)}`)
  .join(',\n');

const header = '// Generated by scripts/write-firebase-config.mjs from environment variables. Do not edit.';

writeFileSync(resolve(root, 'src/app/firebase-config.ts'), `${header}
import type {FirebaseOptions} from 'firebase/app';

export const firebaseConfig: FirebaseOptions = {
${toLines(resolveValues(FIREBASE), '  ')}
};
`);

writeFileSync(resolve(root, 'src/environment.ts'), `${header}
export const environment = {
  target: ${JSON.stringify(target)},
  production: ${target === 'prd'},
  title: ${JSON.stringify(TITLE)},
  databases: {
${toLines(resolveValues(DATABASES), '    ')}
  }
};
`);

console.log(`config written for target "${target}"`);
if (missing.length) {
  console.warn(`empty values for: ${missing.join(', ')}`);
}
